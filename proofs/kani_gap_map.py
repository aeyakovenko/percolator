#!/usr/bin/env python3
"""kani_gap_map.py <engine worktree at the revision> <rev> > specs/kani_gap_map_<rev>.md
Where Kani does not reach, by the call graph (kani_reach.py): the deployed engine functions that no
harness can reach at all, and for every deployed entry point how many harnesses call it and how
many reach it. A first version of this file counted the methods that no proof NAMES; that
overstated the gap several times over, because a harness also executes everything its calls reach."""
import sys, re, os, collections
here = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, here)
wt, rev = sys.argv[1], sys.argv[2]
sys.argv = ["kani_reach.py", wt]
import kani_reach as kr
import transition_kinds as tk
fns, by_id, harness, reached = kr.fns, kr.by_id, kr.harness, kr.reached
size = lambda f: f.text.count("\n") + 1
is_mut = lambda f: "&mut self" in f.text.split("{")[0]
unreached = [f for f in fns if id(f) not in reached]
AREAS = (
    ("Trade execution", r"trade|execute_batch|initial_margin|create_.*lien|settle_account_for_position_action|apply_current_position_delta|plan_delta|position_lookup|side_oi_cap"),
    ("Recovery and forfeit", r"forfeit|recovery|retain_leg_as_pending_obligation|force_"),
    ("Crank steps", r"auto_crank|advance_pending_close|release_account_source_credit_liens|rebalance"),
    ("Terminal routes, canonicalization, resolved clock", r"terminal|canonicalize|recredit|resolved_counterparty_backing_surplus|advance_resolved_slot|activate_empty_asset_slot"),
)
def area(f):
    for name, pat in AREAS:
        if re.search(pat, f.name): return name
    return "Other"
groups = collections.defaultdict(list)
for f in unreached: groups[area(f)].append(f)
eng = open(os.path.join(wt, "src/v16.rs")).read()
rows = [r for r in tk.classify(eng) if r["deployed"] == "yes"]
proof_text = "".join(open(os.path.join(wt, p)).read() for p in ("tests/proofs_v16.rs", "src/v16_proofs.rs"))
def direct(n): return len(re.findall(r"\b" + re.escape(n) + r"\(", proof_text))
def n_reach(n):
    ids = [id(f) for f in kr.by_name.get(n, [])]
    return sum(1 for r in harness.values() if any(i in r for i in ids))
mut_all = [f for f in fns if is_mut(f)]
print(f"""# Where Kani does not reach (engine revision {rev})

Generated by `kani_gap_map.py` from `kani_reach.py`. The Kani suite has {len(harness)} harnesses. This file
orders the prover's work: it goes first where Kani has nothing.

Three measures, from weakest to strongest evidence of a gap:

1. **No harness reaches the function through the call graph.** Certain: Kani never executes it.
   {len(unreached)} of the {len(fns)} deployed engine functions, {sum(1 for f in unreached if is_mut(f))} of the {len(mut_all)} that change state. Listed below.
2. **A harness reaches it, but perhaps never executes it.** The call graph says what a harness could
   call, not what it does: `full_account_refresh_not_atomic` is reached by one harness, which
   proves that a call is rejected before the refresh runs. Only Kani's coverage mode tells
   (`cargo kani --tests --features fuzz --coverage -Z source-coverage`, then `kani_cov_report.py`).
3. **A harness executes it but asserts something else.** Not measured here.

An earlier version of this file (2026-11-20) counted the methods that no proof names, and
reported 124 state-changing methods under five entry points. That count was wrong as a measure of coverage: by the call graph the same five entry
points reach only 18 state-changing methods that no harness reaches.

## Certain gaps: deployed functions no harness can reach
""")
for name, _ in AREAS + (("Other", ""),):
    g = sorted(groups.get(name, []), key=lambda f: -size(f))
    if not g: continue
    print(f"### {name}\n\n{len(g)} functions, {sum(size(f) for f in g)} lines; {sum(1 for f in g if is_mut(f))} change state.\n")
    print("| Lines | Changes state | Function | Line |\n|---|---|---|---|")
    for f in g:
        print(f"| {size(f)} | {'yes' if is_mut(f) else ''} | `{f.name}` | {f.line} |")
    print()
# ------------------------------------------------------------------ what the suite itself calls intractable
print("""## What the proof suite itself records as beyond Kani

The engine's proof files carry notes on proofs that were tried and given up, with the reductions
that were attempted. They are quoted here because they are the map of Kani's limits by the people
who hit them; the prover's first targets are taken from this list and from the certain gaps above.
""")
for path in ("tests/proofs_v16.rs", "src/v16_proofs.rs"):
    lines = open(os.path.join(wt, path)).read().split("\n")
    i = 0
    while i < len(lines):
        if re.search(r"intractable", lines[i], re.I) and lines[i].lstrip().startswith("//"):
            a0 = i
            while a0 > 0 and lines[a0 - 1].lstrip().startswith("//"): a0 -= 1
            b0 = i
            while b0 + 1 < len(lines) and lines[b0 + 1].lstrip().startswith("//"): b0 += 1
            block = [l.strip()[2:].strip() for l in lines[a0:b0 + 1]]
            print(f"**`{path}` lines {a0 + 1} to {b0 + 1}**\n")
            print("> " + "\n> ".join(block) + "\n")
            i = b0 + 1
        else:
            i += 1
print("""In short, in the suite's own words: every transition that changes a pair of accounts or
source-claim state through the real engine structs is beyond Kani's budget, even with fully
concrete inputs. Named there: the application of a trade fill (`apply_trade_after_refresh`), the
body of `full_account_refresh`, the realize, cure and convert bodies (lien creation and
consumption, claim burning), the full resolved close, and the header check
`pnl_pos_bound_tot_num >= pnl_pos_tot * BOUND_SCALE` as a lemma about `validate_shape`.
""")
print("""## Deployed entry points

"Calls" counts harness bodies that call the entry point by name; "reach" counts harnesses that can
reach it through the call graph (through another entry point or the proof API).

| Label | Entry point | Harnesses that call it | Harnesses that reach it |
|---|---|---|---|""")
tab = sorted(((n_reach(r["name"]), direct(r["name"]), r["label"], r["name"]) for r in rows))
for nr, nd, lab, n in tab:
    print(f"| {lab} | `{n}` | {nd} | {nr} |")
zero = [t for t in tab if t[0] == 0]
print(f"\n{len(zero)} of the {len(rows)} deployed entry points are reached by no harness: " + ", ".join(f"`{t[3]}`" for t in zero) + ".")
